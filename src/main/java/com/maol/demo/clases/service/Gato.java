package com.maol.demo.clases.service;

public class Gato {

	private String color;
	private int edad;
	private double numeroPatas;

	public void setColor(String parametroColor) {
		this.color = parametroColor;

	}

	public String getColor() {
		return this.color;
	}

	public void setEdad(int parametroEdad) {
		this.edad = parametroEdad;

	}

	public int getEdad() {
		return this.edad;

	}

	public double getNumeroPatas() {
		return this.numeroPatas;
	}

	public void setNumeroPatas(double parametroNumeroPatas) {
		this.numeroPatas = parametroNumeroPatas;
	}

}
